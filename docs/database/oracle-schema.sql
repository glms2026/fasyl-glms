-- Enterprise General Ledger Management System Oracle Schema
-- Run as the GLMS application schema owner.

CREATE TABLE USERS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50 CHAR) NOT NULL,
    EMAIL VARCHAR2(120 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(100 CHAR) NOT NULL,
    FIRST_NAME VARCHAR2(80 CHAR),
    LAST_NAME VARCHAR2(80 CHAR),
    PHONE_NUMBER VARCHAR2(30 CHAR),
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    ACCOUNT_LOCKED NUMBER(1) DEFAULT 0 NOT NULL,
    FAILED_LOGIN_ATTEMPTS NUMBER(3) DEFAULT 0 NOT NULL,
    LAST_LOGIN_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19),
    UPDATED_AT TIMESTAMP,
    UPDATED_BY NUMBER(19),
    CONSTRAINT UK_USERS_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USERS_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'LOCKED', 'DELETED')),
    CONSTRAINT CK_USERS_LOCKED CHECK (ACCOUNT_LOCKED IN (0, 1))
);

CREATE TABLE ROLES (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(50 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(255 CHAR),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19),
    UPDATED_AT TIMESTAMP,
    UPDATED_BY NUMBER(19),
    CONSTRAINT UK_ROLES_NAME UNIQUE (NAME)
);

CREATE TABLE PERMISSIONS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(80 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(255 CHAR),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19),
    UPDATED_AT TIMESTAMP,
    UPDATED_BY NUMBER(19),
    CONSTRAINT UK_PERMISSIONS_NAME UNIQUE (NAME)
);

CREATE TABLE USER_ROLES (
    USER_ID NUMBER(19) NOT NULL,
    ROLE_ID NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19),
    CONSTRAINT PK_USER_ROLES PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_USER_ROLES_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID),
    CONSTRAINT FK_USER_ROLES_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES(ID)
);

CREATE TABLE ROLE_PERMISSIONS (
    ROLE_ID NUMBER(19) NOT NULL,
    PERMISSION_ID NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19),
    CONSTRAINT PK_ROLE_PERMISSIONS PRIMARY KEY (ROLE_ID, PERMISSION_ID),
    CONSTRAINT FK_ROLE_PERM_ROLE FOREIGN KEY (ROLE_ID) REFERENCES ROLES(ID),
    CONSTRAINT FK_ROLE_PERM_PERMISSION FOREIGN KEY (PERMISSION_ID) REFERENCES PERMISSIONS(ID)
);

CREATE TABLE LEDGER_TYPES (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE VARCHAR2(40 CHAR) NOT NULL,
    NAME VARCHAR2(100 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19),
    UPDATED_AT TIMESTAMP,
    UPDATED_BY NUMBER(19),
    CONSTRAINT UK_LEDGER_TYPES_CODE UNIQUE (CODE)
);

CREATE TABLE LEDGER_CATEGORIES (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE VARCHAR2(40 CHAR) NOT NULL,
    NAME VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(255 CHAR),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19),
    UPDATED_AT TIMESTAMP,
    UPDATED_BY NUMBER(19),
    CONSTRAINT UK_LEDGER_CATEGORIES_CODE UNIQUE (CODE)
);

CREATE TABLE LEDGERS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LEDGER_NUMBER VARCHAR2(60 CHAR) NOT NULL,
    TITLE VARCHAR2(150 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(500 CHAR),
    OWNER_USER_ID NUMBER(19) NOT NULL,
    LEDGER_TYPE_ID NUMBER(19) NOT NULL,
    LEDGER_CATEGORY_ID NUMBER(19),
    DEBIT_AMOUNT NUMBER(19, 4) DEFAULT 0 NOT NULL,
    CREDIT_AMOUNT NUMBER(19, 4) DEFAULT 0 NOT NULL,
    CURRENCY_CODE CHAR(3 CHAR) DEFAULT 'USD' NOT NULL,
    ACCOUNTING_DATE DATE NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
    VERSION NUMBER(19) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY NUMBER(19),
    UPDATED_AT TIMESTAMP,
    UPDATED_BY NUMBER(19),
    CONSTRAINT UK_LEDGERS_NUMBER UNIQUE (LEDGER_NUMBER),
    CONSTRAINT FK_LEDGERS_OWNER FOREIGN KEY (OWNER_USER_ID) REFERENCES USERS(ID),
    CONSTRAINT FK_LEDGERS_TYPE FOREIGN KEY (LEDGER_TYPE_ID) REFERENCES LEDGER_TYPES(ID),
    CONSTRAINT FK_LEDGERS_CATEGORY FOREIGN KEY (LEDGER_CATEGORY_ID) REFERENCES LEDGER_CATEGORIES(ID),
    CONSTRAINT CK_LEDGERS_STATUS CHECK (STATUS IN ('DRAFT', 'POSTED', 'VOIDED', 'DELETED')),
    CONSTRAINT CK_LEDGERS_AMOUNTS CHECK (DEBIT_AMOUNT >= 0 AND CREDIT_AMOUNT >= 0 AND (DEBIT_AMOUNT > 0 OR CREDIT_AMOUNT > 0)),
    CONSTRAINT CK_LEDGERS_CURRENCY CHECK (REGEXP_LIKE(CURRENCY_CODE, '^[A-Z]{3}$'))
);

CREATE TABLE AUDIT_LOGS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACTOR_USER_ID NUMBER(19),
    ACTION VARCHAR2(80 CHAR) NOT NULL,
    ENTITY_TYPE VARCHAR2(80 CHAR) NOT NULL,
    ENTITY_ID NUMBER(19),
    OLD_VALUE CLOB,
    NEW_VALUE CLOB,
    IP_ADDRESS VARCHAR2(60 CHAR),
    USER_AGENT VARCHAR2(500 CHAR),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_AUDIT_ACTOR FOREIGN KEY (ACTOR_USER_ID) REFERENCES USERS(ID)
);

CREATE TABLE PASSWORD_RESET_TOKENS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER(19) NOT NULL,
    TOKEN_HASH VARCHAR2(128 CHAR) NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL,
    USED_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_PASSWORD_RESET_TOKEN UNIQUE (TOKEN_HASH),
    CONSTRAINT FK_PASSWORD_RESET_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID)
);

CREATE TABLE REFRESH_TOKENS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER(19) NOT NULL,
    TOKEN_HASH VARCHAR2(128 CHAR) NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL,
    REVOKED_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY_IP VARCHAR2(60 CHAR),
    REVOKED_BY_IP VARCHAR2(60 CHAR),
    CONSTRAINT UK_REFRESH_TOKEN UNIQUE (TOKEN_HASH),
    CONSTRAINT FK_REFRESH_TOKEN_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID)
);

CREATE INDEX IX_USERS_STATUS ON USERS(STATUS);
CREATE INDEX IX_USER_ROLES_ROLE ON USER_ROLES(ROLE_ID);
CREATE INDEX IX_ROLE_PERM_PERMISSION ON ROLE_PERMISSIONS(PERMISSION_ID);
CREATE INDEX IX_LEDGERS_OWNER ON LEDGERS(OWNER_USER_ID);
CREATE INDEX IX_LEDGERS_OWNER_STATUS ON LEDGERS(OWNER_USER_ID, STATUS);
CREATE INDEX IX_LEDGERS_ACCOUNTING_DATE ON LEDGERS(ACCOUNTING_DATE);
CREATE INDEX IX_AUDIT_ENTITY ON AUDIT_LOGS(ENTITY_TYPE, ENTITY_ID);
CREATE INDEX IX_AUDIT_ACTOR_DATE ON AUDIT_LOGS(ACTOR_USER_ID, CREATED_AT);
CREATE INDEX IX_PASSWORD_RESET_USER ON PASSWORD_RESET_TOKENS(USER_ID);
CREATE INDEX IX_REFRESH_TOKEN_USER ON REFRESH_TOKENS(USER_ID);

